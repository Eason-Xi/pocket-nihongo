# 拗音：前一个 i 段假名 + 小写 ゃゅょ 合成一个音节。
_YOUON_ROMAJI = {
    "きゃ": "kya", "きゅ": "kyu", "きょ": "kyo",
    "しゃ": "sha", "しゅ": "shu", "しょ": "sho",
    "ちゃ": "cha", "ちゅ": "chu", "ちょ": "cho",
    "にゃ": "nya", "にゅ": "nyu", "にょ": "nyo",
    "ひゃ": "hya", "ひゅ": "hyu", "ひょ": "hyo",
    "みゃ": "mya", "みゅ": "myu", "みょ": "myo",
    "りゃ": "rya", "りゅ": "ryu", "りょ": "ryo",
    "ぎゃ": "gya", "ぎゅ": "gyu", "ぎょ": "gyo",
    "じゃ": "ja", "じゅ": "ju", "じょ": "jo",
    "びゃ": "bya", "びゅ": "byu", "びょ": "byo",
    "ぴゃ": "pya", "ぴゅ": "pyu", "ぴょ": "pyo",
}

_VOWELS = "aiueo"


def kata_to_hira(text: str) -> str:
    """把片假名（U+30A1..U+30F6）换算成对应平假名；其他字符原样保留。"""
    out = []
    for char in text:
        code = ord(char)
        out.append(chr(code - 0x60) if 0x30A1 <= code <= 0x30F6 else char)
    return "".join(out)


def hira_to_kata(text: str) -> str:
    """把平假名（U+3041..U+3096）换算成对应片假名；其他字符原样保留。"""
    out = []
    for char in text:
        code = ord(char)
        out.append(chr(code + 0x60) if 0x3041 <= code <= 0x3096 else char)
    return "".join(out)


def to_romaji(kana: str) -> str:
    """把假名串转成平文式罗马音。

    规则：
    * 拗音（き + ゃ）优先匹配两字符；
    * 促音 っ 重复下一个音节的首辅音，ち 系写作 tch（まっちゃ → matcha）；
    * 长音符 ー 重复前一个元音（コーヒー → koohii）；
    * ん 后接元音或 y 时写作 n'，避免 kin'en / kinen 混淆。

    遇到表外字符抛出 ValueError，保证内容里不会混入无法转换的假名。
    """
    text = kata_to_hira(kana)
    syllables: list[str] = []
    index = 0
    geminate = False
    while index < len(text):
        pair = text[index:index + 2]
        char = text[index]
        if pair in _YOUON_ROMAJI:
            roma = _YOUON_ROMAJI[pair]
            index += 2
        elif char == "っ":
            geminate = True
            index += 1
            continue
        elif char == "ー":
            if not syllables or syllables[-1][-1] not in _VOWELS:
                raise ValueError(f"长音符前没有元音: {kana!r}")
            syllables.append(syllables[-1][-1])
            index += 1
            continue
        elif char in _BASE_ROMAJI:
            roma = _BASE_ROMAJI[char]
            index += 1
        else:
            raise ValueError(f"无法转换的字符 {char!r}（U+{ord(char):04X}）: {kana!r}")

        if geminate:
            roma = ("t" + roma) if roma.startswith("ch") else (roma[0] + roma)
            geminate = False
        if syllables and syllables[-1] == "n" and roma[0] in _VOWELS + "y":
            syllables[-1] = "n'"
        syllables.append(roma)
    if geminate:
        raise ValueError(f"促音不能出现在末尾: {kana!r}")
    return "".join(syllables)


