@dataclass(frozen=True)
class KanaGroup:
    """一个假名大类（清音/浊音/半浊音/拗音）。"""

    name: str                  # 中文分类名，显示在卡片左上角
    rows: tuple[str, ...]      # 每一「行」的平假名，空格分隔各音节


KANA_GROUPS: tuple[KanaGroup, ...] = (
    KanaGroup("清音", (
        "あ い う え お", "か き く け こ", "さ し す せ そ", "た ち つ て と",
        "な に ぬ ね の", "は ひ ふ へ ほ", "ま み む め も", "や ゆ よ",
        "ら り る れ ろ", "わ を", "ん",
    )),
    KanaGroup("浊音", (
        "が ぎ ぐ げ ご", "ざ じ ず ぜ ぞ", "だ ぢ づ で ど", "ば び ぶ べ ぼ",
    )),
    KanaGroup("半浊音", ("ぱ ぴ ぷ ぺ ぽ",)),
    KanaGroup("拗音", (
        "きゃ きゅ きょ", "しゃ しゅ しょ", "ちゃ ちゅ ちょ", "にゃ にゅ にょ",
        "ひゃ ひゅ ひょ", "みゃ みゅ みょ", "りゃ りゅ りょ", "ぎゃ ぎゅ ぎょ",
        "じゃ じゅ じょ", "びゃ びゅ びょ", "ぴゃ ぴゅ ぴょ",
    )),
)


@dataclass(frozen=True)
class Kana:
    """一张假名卡片（平假名写法；片假名由 hira_to_kata 派生）。"""

    hira: str        # 平假名，如 "きゃ"
    romaji: str      # 罗马音，如 "kya"
    group: int       # KANA_GROUPS 下标
    row_label: str   # 行标签（平假名写法），如 "か行"；ん 单独为「拨音」


def _row_label(group_name: str, first: str) -> str:
    """行标签：ん 是拨音，其他行用首字 + 「行」（か行、きゃ行）。"""
    if first == "ん":
        return "拨音"
    return f"{first}行"


def build_kana() -> list[Kana]:
    """按表顺序展开全部假名卡片（清音 46 + 浊音 20 + 半浊音 5 + 拗音 33 = 104）。"""
    cards: list[Kana] = []
    for group_index, group in enumerate(KANA_GROUPS):
        for row in group.rows:
            syllables = row.split()
            label = _row_label(group.name, syllables[0])
            for hira in syllables:
                cards.append(Kana(hira, to_romaji(hira), group_index, label))
    return cards


