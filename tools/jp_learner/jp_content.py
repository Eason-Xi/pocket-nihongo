def build_words() -> list[Word]:
    """展开单词表；分类下标取自所在块的位置。"""
    if len(_WORD_TABLE) != len(WORD_CATEGORIES):
        raise ValueError("单词分块数量必须与 WORD_CATEGORIES 一致")
    words: list[Word] = []
    for category, block in enumerate(_WORD_TABLE):
        for row in block:
            word, reading, meaning, *override = row
            words.append(Word(word, reading, meaning, category, override[0] if override else ""))
    return words


